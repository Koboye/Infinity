import assert from 'node:assert/strict';
const { initialCalc, pressCalc, calcKeyFrom } = await import('../src/lib/calc.js');
const type = (keys) => [...keys].reduce(pressCalc, initialCalc());
const show = (keys) => type(keys).cur;

assert.equal(show('12+30='), '42');
assert.equal(show('9−4×3='), '15', 'left to right, like a school calculator');
assert.equal(show('0.1+0.2='), '0.3', 'no floating point noise');
assert.equal(show('8÷0='), 'Error');
assert.equal(show('8÷0=5'), '5', 'any key recovers from Error');
assert.equal(show('7+'), '7');
assert.equal(show('7+×3='), '21', 'changing the operator replaces it');
assert.equal(show('5+3+'), '8', 'chained operators show the running total');
assert.equal(show('123⌫'), '12');
assert.equal(show('1⌫⌫'), '0');
assert.equal(show('5±'), '-5');
assert.equal(show('5±±'), '5');
assert.equal(show('50%'), '0.5');
assert.equal(show('1.2.3'), '1.23', 'one decimal point only');
assert.equal(show('.5+.5='), '1');
assert.equal(show('2+3=4'), '4', 'typing after = starts a new number');
assert.equal(show('2+3=+4='), '9', 'result can be continued');
assert.equal(show('99C'), '0');
assert.equal(show('1'.repeat(20)).length, 15, 'digit limit');
assert.equal(type('2+3=').line, '2 + 3 =');
assert.equal(calcKeyFrom('*'), '×');
assert.equal(calcKeyFrom('Enter'), '=');
assert.equal(calcKeyFrom('a'), '');
console.log('ok calc');
