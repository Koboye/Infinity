const idx = (lang) => (lang === 'am' ? 0 : 1);

export const makeT = (lang) => {
  const t = (key) => (LABELS[key] ? LABELS[key][idx(lang)] : key);
  const tb = (key) => {
    const l = LABELS[key];
    if (!l) return key;
    return lang === 'am' && l[0] !== l[1] ? `${l[0]} · ${l[1]}` : l[idx(lang)];
  };
  return { t, tb };
};
